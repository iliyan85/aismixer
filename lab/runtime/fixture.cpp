#include "fixture.h"

#include <algorithm>
#include <utility>

namespace aismixer::lab::runtime {
Fixture make_synthetic_fixture() {
    Fixture fixture;
    fixture.provenance = "SYNTHETIC INFRASTRUCTURE TEST (NOT AIS RADIO SIMULATION); scripted outcomes; stored qualified B3 Type1 golden";
    fixture.utc_anchor = {1792195199, kUnitsPerSecond / 2};  // Explicit arbitrary half-second anchor.
    fixture.receivers = {{"receiver.R1"}, {"receiver.R2"}, {"receiver.R3"}};
    const std::string station = "station.A";
    const TransmissionId tx{"fixture.tx.1"};
    const auto push = [&](SimulationInstant time, EventKind kind, std::string source, std::string subject,
                          std::uint64_t sequence, std::optional<EventId> cause, EventPayload payload) {
        const auto id = EventId{source, sequence};
        fixture.events.push_back({kEventSchemaVersion, time, kind, std::move(source), std::move(subject), id, std::move(cause), std::move(payload)});
    };
    push({0}, EventKind::StationOn, station, station, 1, std::nullopt, StationLifecycle{station});
    for (const auto& receiver : fixture.receivers)
        push({0}, EventKind::ReceiverOn, receiver.value, receiver.value, 1, std::nullopt, ReceiverLifecycle{receiver});
    // R3 is explicitly silent in this off interval. It is turned on again well
    // before the labelled TX so its later scripted failure is not an off-radio decode.
    push(from_seconds(1), EventKind::ReceiverOff, "receiver.R3", "receiver.R3", 2, std::nullopt, ReceiverLifecycle{{"receiver.R3"}});
    push(from_seconds(2), EventKind::ReceiverOn, "receiver.R3", "receiver.R3", 3, std::nullopt, ReceiverLifecycle{{"receiver.R3"}});
    const auto start = from_seconds(3), end = add_units(start, kUnitsPerSlot);
    push(start, EventKind::TransmissionStart, station, station, 2, EventId{station, 1},
        TransmissionStart{tx, station, 0, end, "fixture.b3.type1.golden"});
    push(end, EventKind::TransmissionEnd, station, station, 3, EventId{station, 2}, TransmissionEnd{tx});
    // This literal is an existing independent B3 acceptance vector, never
    // regenerated by the encoder or by this fixture implementation.
    const std::string sentence = "!AIVDM,1,1,,A,1Amg=5EmQso>f;LFGd5DlSoo7D<Q,0*2B\r\n";
    for (std::size_t index = 0; index < fixture.receivers.size(); ++index) {
        const auto& receiver = fixture.receivers[index];
        const ReceptionId reception{"fixture.rx." + std::to_string(index + 1)};
        const auto sequence = index == 2 ? std::uint64_t{4} : std::uint64_t{2};
        const bool success = index < 2;
        push(end, success ? EventKind::ReceptionSuccess : EventKind::ReceptionFailure,
            receiver.value, receiver.value, sequence, EventId{station, 3},
            ReceptionResult{reception, tx, receiver, end, "Explicit scripted fixture outcome; no RF computation"});
        if (success) push(end, EventKind::ReceiverNmea, receiver.value, receiver.value, sequence + 1,
            EventId{receiver.value, sequence}, ReceiverNmea{receiver, reception, tx, {sentence}});
    }
    for (std::size_t index = 0; index < fixture.receivers.size(); ++index) {
        const auto& receiver = fixture.receivers[index];
        push(from_seconds(4), EventKind::ReceiverOff, receiver.value, receiver.value,
            index == 2 ? 5u : 4u, std::nullopt, ReceiverLifecycle{receiver});
    }
    push(from_seconds(4), EventKind::StationOff, station, station, 4, std::nullopt, StationLifecycle{station});
    std::sort(fixture.events.begin(), fixture.events.end(), CanonicalLess{});
    return fixture;
}

}  // namespace aismixer::lab::runtime
